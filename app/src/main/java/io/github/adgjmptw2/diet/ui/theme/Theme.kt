internal fun appColorScheme(theme: AppTheme): ColorScheme = when (theme) {
    AppTheme.LIGHT -> Light
    AppTheme.DARK -> Dark
    AppTheme.BUNNY -> Bunny
    AppTheme.OCEAN -> Ocean
}

private val AppShapes = Shapes(
    extraSmall = RoundedCornerShape(8.dp),
    small = RoundedCornerShape(12.dp),
    medium = RoundedCornerShape(16.dp),
    large = RoundedCornerShape(20.dp),
    extraLarge = RoundedCornerShape(24.dp),
)

/** 체중 증가 표시용 (감량은 primary) */
val GainColor @Composable get() = MaterialTheme.colorScheme.tertiary

@Composable
fun DietTheme(theme: AppTheme = AppTheme.LIGHT, content: @Composable () -> Unit) {
    CompositionLocalProvider(LocalAppTheme provides theme) {
        MaterialTheme(
            colorScheme = appColorScheme(theme),
            typography = AppTypography,
            shapes = AppShapes,
            content = content,
        )
    }
}
